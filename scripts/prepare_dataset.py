"""Turn a folder of YOLO-labelled card images into a Kaggle-ready dataset.

    python -m scripts.prepare_dataset --src E:/data/cards --out E:/data/ir-card-yolo

Produces:

    out/
      data.yaml          class names in the document profile's order
      train/images  train/labels
      val/images    val/labels
      test/images   test/labels     (only with --test-split > 0)

The class order in `data.yaml` is taken from the document profile, not from
whatever the labelling tool happened to emit. If your source labels use a
different order, pass `--source-names` and the class ids are remapped as the
files are copied - which fixes the mismatch instead of just reporting it.

Input layout: either `src/images/*.jpg` + `src/labels/*.txt`, or a flat folder
where each `foo.jpg` sits next to its `foo.txt`.
"""

from __future__ import annotations

import argparse
import random
import shutil
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from kyc.modules.ocr.profiles import get_profile  # noqa: E402

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def find_pairs(src: Path) -> list[tuple[Path, Path | None]]:
    """Match every image with its label file, if there is one."""
    images_dir = src / "images" if (src / "images").is_dir() else src
    labels_dir = src / "labels" if (src / "labels").is_dir() else src

    pairs: list[tuple[Path, Path | None]] = []
    for image in sorted(p for p in images_dir.rglob("*") if p.suffix.lower() in IMAGE_SUFFIXES):
        label = labels_dir / f"{image.stem}.txt"
        pairs.append((image, label if label.exists() else None))
    return pairs


def parse_label(path: Path) -> list[tuple[int, str]]:
    """Return (class_id, rest-of-line) for each annotation."""
    rows: list[tuple[int, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        head, _, rest = line.partition(" ")
        try:
            rows.append((int(head), rest))
        except ValueError:
            print(f"[warn] {path.name}: cannot parse class id in {line!r}; line skipped")
    return rows


def build_remap(source_names: list[str], target_names: tuple[str, ...]) -> dict[int, int]:
    unknown = [n for n in source_names if n not in target_names]
    if unknown:
        raise SystemExit(
            f"These source class names are not in the profile: {unknown}\n"
            f"Profile classes: {list(target_names)}"
        )
    return {i: target_names.index(name) for i, name in enumerate(source_names)}


def write_data_yaml(out: Path, class_names: tuple[str, ...], splits: list[str]) -> None:
    lines = [
        "# Generated by scripts/prepare_dataset.py",
        "# Class order matches the document profile. Do not reorder: the",
        "# serving pipeline maps class index -> field by this exact list.",
        f"path: {out.as_posix()}",
    ]
    for split in splits:
        lines.append(f"{split}: {split}/images")
    lines.append("names:")
    lines.extend(f"  {index}: {name}" for index, name in enumerate(class_names))
    (out / "data.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src", required=True, help="Folder with labelled images")
    parser.add_argument("--out", required=True, help="Destination dataset folder")
    parser.add_argument("--profile", default="ir_national_card_front")
    parser.add_argument(
        "--source-names",
        default=None,
        help="Comma-separated class order used by the SOURCE labels, if it differs from the profile",
    )
    parser.add_argument("--val-split", type=float, default=0.15)
    parser.add_argument("--test-split", type=float, default=0.0)
    parser.add_argument("--seed", type=int, default=1337)
    parser.add_argument("--skip-unlabelled", action="store_true", help="Drop images with no label file")
    args = parser.parse_args()

    profile = get_profile(args.profile)
    class_names = profile.class_names
    src, out = Path(args.src), Path(args.out)
    if not src.is_dir():
        raise SystemExit(f"Source folder not found: {src}")

    remap: dict[int, int] | None = None
    if args.source_names:
        source_names = [n.strip() for n in args.source_names.split(",") if n.strip()]
        remap = build_remap(source_names, class_names)
        print(f"[remap] {dict(sorted(remap.items()))}")

    pairs = find_pairs(src)
    if not pairs:
        raise SystemExit(f"No images found under {src}")

    unlabelled = [image for image, label in pairs if label is None]
    if unlabelled:
        action = "dropped" if args.skip_unlabelled else "kept as background images"
        print(f"[info] {len(unlabelled)} image(s) have no label file; {action}")
        if args.skip_unlabelled:
            pairs = [(image, label) for image, label in pairs if label is not None]

    random.Random(args.seed).shuffle(pairs)
    total = len(pairs)
    n_val = int(total * args.val_split)
    n_test = int(total * args.test_split)
    splits = {
        "val": pairs[:n_val],
        "test": pairs[n_val:n_val + n_test],
        "train": pairs[n_val + n_test:],
    }
    if not splits["test"]:
        splits.pop("test")

    if out.exists():
        shutil.rmtree(out)
    counts: Counter[str] = Counter()
    bad_ids = 0

    for split, items in splits.items():
        (out / split / "images").mkdir(parents=True)
        (out / split / "labels").mkdir(parents=True)
        for image, label in items:
            shutil.copy2(image, out / split / "images" / image.name)
            if label is None:
                # An empty label file is how YOLO expresses "no objects here".
                (out / split / "labels" / f"{image.stem}.txt").write_text("", encoding="utf-8")
                continue
            lines = []
            for class_id, rest in parse_label(label):
                mapped = remap.get(class_id, class_id) if remap else class_id
                if not 0 <= mapped < len(class_names):
                    bad_ids += 1
                    continue
                counts[class_names[mapped]] += 1
                lines.append(f"{mapped} {rest}")
            (out / split / "labels" / f"{image.stem}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    write_data_yaml(out, class_names, list(splits))

    print(f"\n[done] {out}")
    for split, items in splits.items():
        print(f"  {split:<6} {len(items):5d} images")
    print("\n  annotations per class:")
    for name in class_names:
        count = counts.get(name, 0)
        flag = "   <-- NONE" if count == 0 else ""
        print(f"    {name:<14} {count:6d}{flag}")

    problems = 0
    missing = [n for n in class_names if counts.get(n, 0) == 0]
    if missing:
        print(f"\n[error] no annotations at all for: {missing}")
        print("        The detector cannot learn a class it never sees; the pipeline")
        print("        will report those fields as not located on every card.")
        problems += 1
    if bad_ids:
        print(f"\n[error] {bad_ids} annotation(s) had a class id outside the profile and were dropped")
        problems += 1

    print("\nNext:")
    print("  1. upload this folder to Kaggle as a private dataset")
    print("  2. python -m scripts.kaggle_run push --data-dataset <owner>/<slug>")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
